def legend_three_columns(handles, labels):
    """Reorder row-major items for Matplotlib's column-major legend layout."""
    n = len(handles)
    rows = (n + 2) // 3
    order = [r*3 + c for c in range(3) for r in range(rows)
             if r*3 + c < n]
    return [handles[i] for i in order], [labels[i] for i in order]


def object_gray_palette(object_ids):
    """Give neighboring object IDs visibly contrasting grayscale shades.

    A short, non-monotonic palette is preferable to a fine linear gradient:
    with hundreds of objects, consecutive values in a gradient are otherwise
    almost identical. IDs are stable across TOP and PROFILE views.
    """
    unique = sorted({int(oid) for oid in object_ids if int(oid) > 0})
    # Contrasting grays (dark/medium/light) without near-white tones.
    # Each object_id has a stable shade in TOP and PROFILE.
    gray_levels = (0.10, 0.15, 0.20, 0.25, 0.30,
                   0.35, 0.40, 0.45, 0.50, 0.55)
    return {oid: (gray_levels[i % len(gray_levels)],) * 3
            for i, oid in enumerate(unique)}


def finish_figure(fig, axes, handles, labels, handlers, path, plot_height=7, columns=2,
                  dpi=170, title=None):
    """Separate legend band, sized to fit text without covering plotting area."""
    width = fig.get_figwidth()
    # Measure legend independently from the final axis viewport.
    wrap_width = 47 if columns == 3 else (58 if columns == 2 else 105)
    # Matplotlib fills each column top-to-bottom; expand columns across the plot width.
    lines = [textwrap.fill(str(s), width=wrap_width, break_long_words=False,
                           break_on_hyphens=False) for s in labels]
    fig.set_size_inches(width, plot_height + 9, forward=True)
    leg = fig.legend(handles, lines, loc='lower left',
                     bbox_to_anchor=(.06, .05, .90, 0.), bbox_transform=fig.transFigure,
                     mode="expand", ncol=columns, handler_map=handlers,
                     fontsize=19, handlelength=2.9, handletextpad=.65, labelspacing=1.15,
                     columnspacing=.65, borderaxespad=0., frameon=False)
    fig.canvas.draw()
    leg_h = leg.get_window_extent(renderer=fig.canvas.get_renderer()).height / fig.dpi
    legend_bottom = .55
    gap = .85
    title_space = 1.10
    actual_h = plot_height + leg_h + legend_bottom + gap + title_space
    fig.set_size_inches(width, actual_h, forward=True)
    for ax in axes:
        ax.set_position((.06, (legend_bottom + leg_h + gap)/actual_h,
                         .90, plot_height/actual_h))
    leg.set_bbox_to_anchor((.06, legend_bottom/actual_h, .90, 0.),
                           transform=fig.transFigure)
    if title:
        fig.suptitle(title, fontsize=24, weight='bold', y=1.-.43/actual_h)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=dpi, bbox_inches='tight', pad_inches=.20, facecolor='white')
    plt.close(fig)


def read_ply(path):
    v = PlyData.read(str(path), mmap='r')['vertex'].data
    required = ['x', 'y', 'z', 'class', 'section_id', 'object_id',
                'is_dms', 'wire_id', 'level_id']
    missing = [k for k in required if k not in v.dtype.names]
    if missing:
        raise ValueError(f'The PLY is not the output of zones.py; missing: {missing}')
    xyz = np.column_stack((v['x'], v['y'], v['z'])).astype(np.float64)
    props = {k: np.asarray(v[k]) for k in required[3:]}
    if 'is_cp' in v.dtype.names:
        props['is_cp'] = np.asarray(v['is_cp'])
    else:
        props['is_cp'] = np.isin(props['class'], list(CP_LABELS.values())).astype(np.uint8)
    if 'cp_rank' in v.dtype.names:
        props['cp_rank'] = np.asarray(v['cp_rank'])
    return xyz, props


def cp_records(section, box, xyz, props, pole_gps):
    """Cross-check PLY critical points against per-level JSON XYZ coordinates.

    The JSON intentionally contains no PLY row IDs, ranks, or CP distances.
    Match CPs using their section/object/wire/level and XYZ coordinates, while
    retaining PLY indices and ranks internally for visualization and TXT export.
    """
    sid = int(section['section_id'])
    entries = []
    cp_in_section = np.flatnonzero(
        (props['section_id'] == sid) & (props['is_cp'] == 1) &
        np.isin(props['class'], list(CP_LABELS.values())))
    grouped = {}
    for idx in cp_in_section:
        oid = int(props['object_id'][idx])
        grouped.setdefault(oid, []).append(int(idx))

    for obj in section['collisions']:
        oid = int(obj['object_id'])
        cp_indices = grouped.pop(oid, [])
        expected_by_pair = {}
        for cable, wire_data in obj['wires_affected'].items():
            wid = wire_number(cable)
            if wid not in (1, 2, 3):
                raise ValueError(f'Section {sid}, object {oid}: invalid wire {cable}')
            for level_key, meta in wire_data['levels'].items():
                if not level_key.startswith('level_'):
                    raise ValueError(f'Section {sid}, object {oid}: invalid level {level_key}')
                lev = int(level_key.removeprefix('level_'))
                records = meta['critical_points']
                if records is not None and not isinstance(records, list):
                    raise ValueError(f'Section {sid}, object {oid}: critical_points must be a list or null')
                expected_by_pair[(wid, lev)] = records or []

        actual_by_pair = {}
        for idx in cp_indices:
            wid, lev = int(props['wire_id'][idx]), int(props['level_id'][idx])
            if wid not in (1, 2, 3) or lev < 0 or not props['is_dms'][idx]:
                raise ValueError(f'Section {sid}, object {oid}: invalid PLY critical point at row {idx}')
            actual_by_pair.setdefault((wid, lev), []).append(idx)

        if set(actual_by_pair) - set(expected_by_pair):
            raise ValueError(f'Section {sid}, object {oid}: unexpected PLY wire/level critical points')

        for pair, records in expected_by_pair.items():
            actual_indices = actual_by_pair.get(pair, [])
            if len(records) != len(actual_indices):
                raise ValueError(
                    f'Section {sid}, object {oid}, L{pair[0]}/level_{pair[1]}: '
                    f'JSON has {len(records)} CPs, PLY has {len(actual_indices)}')
            if not records:
                continue
            expected_xyz = []
            for record in records:
                if not isinstance(record, dict) or set(record) != {'xyz'}:
                    raise ValueError('Every JSON critical point must contain only xyz')
                coords = np.asarray(record['xyz'], dtype=np.float64)
                if coords.shape != (3,) or not np.isfinite(coords).all():
                    raise ValueError('Critical-point xyz must contain three finite values')
                expected_xyz.append(coords)
            expected_xyz = np.asarray(expected_xyz)
            actual_xyz = np.asarray(xyz[actual_indices], dtype=np.float64)
            distances, neighbors = cKDTree(actual_xyz).query(expected_xyz, k=1)
            if (np.any(distances > CP_XYZ_TOLERANCE_M) or len(set(map(int, neighbors))) != len(records)):
                raise ValueError(f'Section {sid}, object {oid}: JSON and PLY critical-point XYZ mismatch')

            meta = obj['wires_affected'][f'L{pair[0]}']['levels'][f'level_{pair[1]}']
            for neighbor in neighbors:
                idx = int(actual_indices[int(neighbor)])
                local_xyz = world_to_local(xyz[idx][None, :], box)[0]
                gps_start = pole_gps.get(int(section['from_pole']))
                gps_end = pole_gps.get(int(section['to_pole']))
                # Distance remains a JSON level summary, not a PLY vertex property.
                selected_distance = meta['min_distance_m']
                entries.append({
                    'object': obj, 'object_id': oid, 'index': idx,
                    'wire': pair[0], 'level': pair[1],
                    'min_dist': (float(selected_distance) if selected_distance is not None else float('nan')),
                    'xyz': np.asarray(xyz[idx], dtype=np.float64),
                    'local': local_xyz,
                    'gps': interpolate_gps(gps_start, gps_end,
                                           float(local_xyz[0]), box['length_axis']),
                    'rank_in_object': (int(props['cp_rank'][idx])
                                       if 'cp_rank' in props else int(idx)),
                })

    if grouped:
        raise ValueError(f'Section {sid}: PLY CPs found outside JSON objects: {list(grouped)[:8]}')
    entries.sort(key=lambda item: (float(item['local'][0]),
                                   item['object_id'], item['rank_in_object']))
    for number, entry in enumerate(entries, 1):
        entry['number'] = number
    return entries


def _schematic_cp_layout(entries, length_axis):
    """Compact metro-style arrangement; CP projection stays on its true x."""
    ordered = sorted(entries, key=lambda e: (float(e['local'][0]), e['number']))
    # Place close CPs on opposite sides, rather than far away from the route.
    last = {1: -float('inf'), -1: -float('inf')}
    layout = []
    for entry in ordered:
        x = float(np.clip(entry['local'][0], 0., length_axis))
        side = max((1, -1), key=lambda sign: x - last[sign])
        if x - last[side] < TOP_MAP_LABEL_MIN_X_GAP:
            # A small second lane only when both sides are occupied.
            lane = 1
        else:
            lane = 0
        last[side] = x
        layout.append((entry, x, side, lane))
    return layout




def view_top_map_schematic(path, section, box, entries, pole_gps):
    """Export the schematic TOP-map view requested by the user.

    The Esri WorldStreetMap background is aligned to the LiDAR local frame
    using the GPS of the endpoint poles. The schematic foreground contains
    only the route, endpoint poles and projected critical points.
    """
    sid = int(section['section_id'])
    from_id, to_id = int(section['from_pole']), int(section['to_pole'])
    from_height, to_height = box['from_height'], box['to_height']
    x_min = -TOP_MAP_X_MARGIN
    x_max = box['length_axis'] + TOP_MAP_X_MARGIN
    y_min, y_max = -box['width'] / 2.0, box['width'] / 2.0
    span_x, span_y = x_max - x_min, y_max - y_min
    base_w = 27.
    plot_h = float(np.clip((base_w - 1.5) * span_y / max(span_x, 1e-9), 5., 18.))
    fig, ax = plt.subplots(figsize=(base_w, plot_h + 3))
    fig.patch.set_facecolor('white')
    ax.set_facecolor(TOP_MAP_BACKGROUND)
    # Draw streets FIRST so route, pole markers and CP labels remain visible.
    draw_top_street_basemap(ax, section, box, pole_gps or {},
                            (x_min, x_max), (y_min, y_max))
    handles, labels, handlers = [], [], {}

    # Transit-style guide line between pole bases.
    ax.plot([0., box['length_axis']], [0., 0.], color=TOP_MAP_ROUTE_COLOR,
            linewidth=TOP_MAP_ROUTE_WIDTH, solid_capstyle='round', zorder=1)

    # Legend: start pole first.
    start_handle = Line2D([], [], linestyle='None', alpha=0)
    handles.append(start_handle)
    labels.append(f"START: Pole {from_id} (h={from_height:.2f} m)" if from_height is not None
                  else f"START: Pole {from_id} (h=unavailable)")
    handlers[start_handle] = PoleLegend(from_id)

    show_ids = {e['index'] for e in sorted(entries,
                key=lambda e: (e['level'], e['min_dist'], e['index']))[:MAX_CP_ANNOTATIONS]}

    callout_groups = []
    for entry, x, side, lane in _schematic_cp_layout(entries, box['length_axis']):
        cp_color = LEVEL_COLOR[int(entry['level'])]
        # Projected CP point on the route.
        ax.scatter([x], [0.], s=TOP_MAP_STATION_DOT_SIZE,
                   c=[TOP_MAP_STATION_DOT_COLOR], linewidths=0, zorder=3)
        # Separate leader line, numbered station and diagonal class name.
        number_y = side * (TOP_MAP_CP_LABEL_OFFSET + lane * TOP_MAP_SECOND_LANE_OFFSET)
        connector, = ax.plot([x, x], [0., number_y - side * .55],
                             color='#222222', linewidth=1.8, zorder=2)
        circle = ax.annotate(
            str(entry['number']), (x, number_y), xytext=(0, 0),
            textcoords='offset points', fontsize=TOP_MAP_CP_NUMBER_FONT_SIZE,
            ha='center', va='center', color='black', weight='bold', zorder=5,
            bbox=dict(boxstyle='circle,pad=.42', facecolor=cp_color,
                      edgecolor='black', linewidth=1.8))
        class_name = str(entry['object']['class_name'])
        class_text = ax.text(
            x + .35, number_y + side * TOP_MAP_CLASS_LABEL_GAP,
            class_name, rotation=TOP_MAP_CLASS_LABEL_ROTATION,
            rotation_mode='anchor', fontsize=TOP_MAP_CLASS_FONT_SIZE,
            fontstyle=TOP_MAP_CLASS_FONT_STYLE,
            fontweight='bold', color=TOP_MAP_CLASS_COLOR,
            ha='left', va='bottom' if side > 0 else 'top', zorder=4,
            bbox=dict(facecolor='white', edgecolor='none', alpha=.65, pad=.8))
        callout_groups.append((x, side, circle, class_text, connector))
        if entry['index'] in show_ids:
            label = (f"COL {sid} - DMS {entry['number']}: "
                     f"{class_name} - "
                     f"Level {entry['level']} "
                     f"(x_col={float(entry['local'][0]):.2f} m, "
                     f"y_col={float(entry['local'][1]):.2f} m, "
                     f"min_dist_L{entry['wire']}={entry['min_dist']:.2f} m)")
            dummy = Line2D([], [], linestyle='None', marker='o', alpha=0)
            handles.append(dummy)
            labels.append(label)
            handlers[dummy] = NumberLegend(entry['number'], cp_color)

    if len(entries) > len(show_ids):
        handles.append(Line2D([], [], linestyle='None', marker='o', color='black'))
        labels.append(f'{len(entries):,} total CPs: only {len(show_ids)} numbered here. '
                      'Every CP is projected and plotted; consult TXT/JSON for the full list.')

    delta_d = float(np.linalg.norm(np.asarray(box['end_base']) - np.asarray(box['origin'])))
    end_handle = Line2D([], [], linestyle='None', alpha=0)
    handles.append(end_handle)
    end_h = f"{to_height:.2f} m" if to_height is not None else "unavailable"
    labels.append(f"END: Pole {to_id} (h={end_h}, Δd={delta_d:.2f} m)")
    handlers[end_handle] = PoleLegend(to_id)

    # Place pole labels outside the span, not over the CP markers or route.
    # The black anchor dot remains at the actual pole base on the blue line.
    for pole_id, pole_x, direction in (
            (from_id, 0., -1.), (to_id, box['length_axis'], 1.)):
        ax.scatter([pole_x], [0.], s=TOP_MAP_POLE_DOT_SIZE,
                   c='black', linewidths=0, zorder=7)
        label_x = pole_x + direction * TOP_MAP_POLE_SIDE_OFFSET
        label_y = TOP_MAP_POLE_LABEL_Y
        ax.annotate(f'P{pole_id}', (label_x, label_y), xytext=(0, 0),
                    textcoords='offset points',
                    fontsize=TOP_MAP_POLE_FONT_SIZE, weight='bold',
                    color='black', ha='center', va='bottom',
                    bbox=dict(boxstyle='round,pad=.3', facecolor='#a5ddff',
                              edgecolor='black', linewidth=1.2), zorder=9,
                    annotation_clip=False)

    ax.set_xlim(x_min, x_max)
    ax.set_ylim(y_min, y_max)
    ax.set_xlabel("X' Coordinate (m)", fontsize=16, fontweight='bold', labelpad=12)
    ax.set_ylabel('Schematic offset (m)', fontsize=16, fontweight='bold', labelpad=12)
    ax.set_aspect('equal', adjustable='box')
    ax.xaxis.set_major_locator(MultipleLocator(10.))
    ax.yaxis.set_major_locator(MultipleLocator(5.))
    ax.tick_params(axis='both', labelsize=13)
    ax.grid(True, alpha=.18)
    finish_figure(fig, [ax], handles, labels, handlers, path,
                  plot_height=plot_h, columns=3, dpi=TOP_MAP_DPI,
                  title=f'TOP MAP SCHEMATIC - Collision {sid}')


def draw_top_street_basemap(ax, section, box, pole_gps, xlim, ylim):
    """Warp Esri streets into the LiDAR section's local (X', Y') coordinates.

    GPS endpoints anchor translation, rotation and scale. This assumes the LiDAR
    section and the two surveyed GPS poles describe the same straight span.
    """
    start = pole_gps.get(int(section['from_pole']))
    end = pole_gps.get(int(section['to_pole']))
    if start is None or end is None:
        warn(f"Section {section['section_id']}: no street map (missing pole GPS)")
        return
    try:
        import contextily as ctx
        from pyproj import Transformer

        # coords.txt contains latitude, longitude; pyproj always_xy expects lon, lat.
        to_merc = Transformer.from_crs('EPSG:4326', 'EPSG:3857', always_xy=True)
        sx, sy = to_merc.transform(start[1], start[0])
        ex, ey = to_merc.transform(end[1], end[0])
        delta = np.array([ex - sx, ey - sy], dtype=float)
        span = float(np.linalg.norm(delta))
        if span < 0.1 or box['length_axis'] <= 0:
            raise ValueError('invalid GPS pole separation')
        direction = delta / span
        normal = np.array([-direction[1], direction[0]])
        # Account for Web Mercator's local scale; endpoints match exactly.
        meters_to_merc = span / float(box['length_axis'])
        corners = np.array([[x, y] for x in xlim for y in ylim], dtype=float)
        merc_corners = (np.array([sx, sy]) + meters_to_merc *
                        (corners[:, 0, None] * direction + corners[:, 1, None] * normal))
        west, south = merc_corners.min(axis=0)
        east, north = merc_corners.max(axis=0)
        pad = max(2., .015 * max(east - west, north - south))
        west -= pad; east += pad; south -= pad; north += pad
        # Prefer the highest native Esri detail rather than contextily's auto zoom.
        # A tile budget prevents accidentally requesting hundreds of tiles.
        # Fall back only if a level is unavailable or its coverage is excessive.
        tiles = extent = zoom = None
        errors = []
        provider = ctx.providers.Esri.WorldStreetMap
        max_provider_zoom = int(provider.get('max_zoom', TOP_MAP_ZOOM))
        for candidate in range(min(TOP_MAP_ZOOM, max_provider_zoom), 15, -1):
            try:
                tile_count = ctx.howmany(west, south, east, north,
                                         candidate, ll=False, verbose=False)
                if tile_count > TOP_MAP_MAX_TILES:
                    errors.append(f'z{candidate}: {tile_count} tiles exceeds limit')
                    continue
                image, image_extent = ctx.bounds2img(
                    west, south, east, north, zoom=candidate,
                    source=provider, ll=False, use_cache=True)
                # Do not accept a fully transparent or empty returned raster.
                if image.size == 0 or (image.shape[2] >= 4 and
                                       not np.any(image[:, :, 3])):
                    raise ValueError('empty tiles')
                tiles, extent, zoom = image, image_extent, candidate
                break
            except Exception as tile_exc:
                errors.append(f'z{candidate}: {tile_exc}')
        if tiles is None:
            raise RuntimeError('No usable Esri street tiles: ' + '; '.join(errors))
        if errors:
            warn(f"Section {section['section_id']}: map fallback: " + '; '.join(errors))
        native_m_per_px = (extent[1] - extent[0]) / tiles.shape[1]
        # Resample tile image into the rotated local section frame.
        # Sample at approximately the final plot's pixel density, avoiding
        # a second enlargement of a small intermediate map image.
        nx = min(6500, max(1000, int(TOP_MAP_DPI * ax.figure.get_figwidth() * .90)))
        ny = min(4200, max(400, int(nx * (ylim[1]-ylim[0]) / max(xlim[1]-xlim[0], 1e-6))))
        if nx * ny > TOP_MAP_MAX_PIXELS:
            factor = (TOP_MAP_MAX_PIXELS / (nx * ny)) ** .5
            nx, ny = max(2, int(nx * factor)), max(2, int(ny * factor))
        xx = np.linspace(xlim[0], xlim[1], nx)
        yy = np.linspace(ylim[1], ylim[0], ny)  # top row is northward in image
        gx, gy = np.meshgrid(xx, yy)
        mx = sx + meters_to_merc * (gx * direction[0] + gy * normal[0])
        my = sy + meters_to_merc * (gx * direction[1] + gy * normal[1])
        left, right, bottom, top = extent
        # Tiles represent pixel centers, not the corners of the full extent.
        rows = (top - my) / (top - bottom) * tiles.shape[0] - .5
        cols = (mx - left) / (right - left) * tiles.shape[1] - .5
        sampled = np.stack([map_coordinates(tiles[:, :, channel], [rows, cols],
                                            order=3, mode='nearest', prefilter=True)
                            for channel in range(3)], axis=-1).astype(np.uint8)
        ax.imshow(sampled, extent=(*xlim, *ylim), origin='upper',
                  interpolation='none', alpha=TOP_MAP_OPACITY, zorder=0,
                  aspect='auto')
        ax.text(.995, .008, 'Map tiles © Esri and contributors',
                transform=ax.transAxes, ha='right', va='bottom', fontsize=9,
                color='#333333', zorder=12,
                bbox=dict(facecolor='white', edgecolor='none', alpha=.7, pad=2))
    except Exception as exc:
        warn(f"Section {section['section_id']}: street basemap unavailable: {exc}")


def view_section(path, section, box, xyz, props, entries, recon_indices, axis_y='y', pole_gps=None, show_street_map=False):
    """Aligned-box TOP/PROFILE with section objects in grayscale and DMS priority overlay."""
    sid = int(section['section_id'])
    yi = 1 if axis_y == 'y' else 2

    if axis_y == 'y' and show_street_map and TOP_MAP_SCHEMATIC:
        view_top_map_schematic(path, section, box, entries, pole_gps)
        return

    # Reconstruction points (24-27) already handled separately.
    recon_local = world_to_local(xyz[recon_indices], box)
    keep = inside_box(recon_local, box)
    rids, rloc = recon_indices[keep], recon_local[keep]

    # All non-reconstruction object points assigned to this section, for gray object context.
    obj_ids_all = np.flatnonzero((props['section_id'] == sid) & (props['object_id'] > 0) &
                                 ~np.isin(props['class'], list(RECON.keys())))
    oloc = world_to_local(xyz[obj_ids_all], box)
    keep = inside_box(oloc, box)
    oids_idx = obj_ids_all[keep]
    oloc = oloc[keep]
    oids_val = props['object_id'][oids_idx].astype(np.int64, copy=False)

    # All DMS points of affected physical objects (all wires and all levels).
    # Vectorized section mask: avoids a full-PLY scan per CP.
    dids = np.flatnonzero((props['section_id'] == sid) &
                          (props['object_id'] > 0) &
                          (props['is_dms'] == 1))
    dloc = world_to_local(xyz[dids], box)
    keep = inside_box(dloc, box)
    dids, dloc = dids[keep], dloc[keep]

    x_min, x_max = BOX_X_MIN, box['length_axis'] + BOX_X_MAX
    y_min, y_max = ((-box['width']/2., box['width']/2.) if axis_y == 'y'
                    else (0., box['height']))
    span_x, span_y = x_max - x_min, y_max - y_min
    base_w = 27.
    plot_h = float(np.clip((base_w - 1.5) * span_y / max(span_x, 1e-9), 4., 30.))
    fig, ax = plt.subplots(figsize=(base_w, plot_h + 3))
    fig.patch.set_facecolor('white')
    ax.set_facecolor('white')
    handles, labels, handlers = [], [], {}

    # 1) Draw section objects first, in different gray tones, lowest priority.
    gray_map = object_gray_palette(oids_val)
    for oid in sorted(gray_map):
        mask = oids_val == oid
        if np.any(mask):
            ax.scatter(oloc[mask, 0], oloc[mask, yi],
                       s=5, c=[gray_map[oid]], alpha=.85,
                       linewidths=0, rasterized=True, zorder=1.5)

    # 2) Ground/profile line.
    if axis_y == 'z':
        ax.plot([0., box['length_axis']], [0., box['z2_local']],
                color='gray', linewidth=3., solid_capstyle='round', zorder=1.8)

    # 3) Reconstruction context.
    recon_pole_id = next(ident for ident, name in RECON.items() if name == "Reconstruction MV Poles")
    recon_arm_id = next(ident for ident, name in RECON.items() if name == "Reconstruction MV Crossarms")
    pole_mask = props['class'][rids] == recon_pole_id
    pole_xyz = rloc[pole_mask]
    if len(pole_xyz):
        start_dist = np.sum(pole_xyz**2, axis=1)
        end_point = np.array([box['length_axis'], 0., box['z2_local']])
        end_dist = np.sum((pole_xyz - end_point)**2, axis=1)
        for which, mask, pole_id, height in (
            ('START', start_dist <= end_dist, section['from_pole'], box['from_height']),
            ('END', end_dist < start_dist, section['to_pole'], box['to_height'])):
            if np.any(mask):
                ax.scatter(pole_xyz[mask, 0], pole_xyz[mask, yi], s=50,
                           c=[RECON_COLOR[recon_pole_id]], alpha=.9, linewidths=0,
                           rasterized=True, zorder=4)

    for cls in RECON:
        if cls == recon_pole_id:
            continue
        mask = props['class'][rids] == cls
        if np.any(mask):
            ax.scatter(rloc[mask, 0], rloc[mask, yi],
                       s=50 if cls == recon_arm_id else 1.,
                       c=[RECON_COLOR[cls]], alpha=.85,
                       linewidths=0, rasterized=True, zorder=3.5)

    # 4) DMS priority overlay: green -> yellow -> orange -> red, so red stays on top.
    for lev in (3, 2, 1, 0):
        mask = props['level_id'][dids] == lev
        if np.any(mask):
            ax.scatter(dloc[mask, 0], dloc[mask, yi], s=15,
                       c=[LEVEL_COLOR[lev]], alpha=.88,
                       linewidths=0, rasterized=True,
                       zorder={3: 5.0, 2: 5.2, 1: 5.4, 0: 5.6}[lev])

    # Legend: start pole first.
    from_id, to_id = section['from_pole'], section['to_pole']
    from_height, to_height = box['from_height'], box['to_height']
    start_handle = Line2D([], [], linestyle='None', alpha=0)
    handles.append(start_handle)
    labels.append(f"START: Pole {from_id} (h={from_height:.2f} m)" if from_height is not None
                  else f"START: Pole {from_id} (h=unavailable)")
    handlers[start_handle] = PoleLegend(from_id)

    # 5) Draw every CP as a colored, black-outlined marker.
    # With potentially thousands of CPs, only annotate the top few so the
    # image and 3-column legend remain readable and fit in memory.
    for lev in (3, 2, 1, 0):
        layer = [e for e in entries if e['level'] == lev]
        if not layer:
            continue
        coords = np.array([e['local'] for e in layer])
        ax.scatter(coords[:, 0], coords[:, yi], s=60 if len(entries) > 200 else 150,
                   c=LEVEL_COLOR[lev], edgecolors='black', linewidths=.75,
                   rasterized=True, zorder=8)
    # Prioritize level 0 before 1/2/3, then closest wire distance.
    show_ids = {e['index'] for e in sorted(entries,
                key=lambda e: (e['level'], e['min_dist'], e['index']))[:MAX_CP_ANNOTATIONS]}
    for entry in entries:
        if entry['index'] not in show_ids:
            continue
        cx, cy = float(entry['local'][0]), float(entry['local'][yi])
        cp_color = LEVEL_COLOR[int(entry['level'])]
        ax.annotate(str(entry['number']), (cx, cy), xytext=(0, 19),
                    textcoords='offset points', fontsize=14, ha='center',
                    va='bottom', color='black', weight='bold', zorder=10,
                    bbox=dict(boxstyle='circle,pad=.38', facecolor=cp_color,
                              edgecolor='black', linewidth=1.0))
        x_col = float(entry['local'][0])
        vertical_col = float(entry['local'][yi])
        vertical_name = 'y_col' if axis_y == 'y' else 'z_col'
        label = (f"COL {sid} - DMS {entry['number']}: "
                 f"{entry['object']['class_name']} - "
                 f"Level {entry['level']} "
                 f"(x_col={x_col:.2f} m, {vertical_name}={vertical_col:.2f} m, "
                 f"min_dist_L{entry['wire']}={entry['min_dist']:.2f} m)")
        dummy = Line2D([], [], linestyle='None', marker='o', alpha=0)
        handles.append(dummy)
        labels.append(label)
        handlers[dummy] = NumberLegend(entry['number'], cp_color)
    if len(entries) > len(show_ids):
        handles.append(Line2D([], [], linestyle='None', marker='o', color='black'))
        labels.append(f'{len(entries):,} total CPs: only {len(show_ids)} numbered here. '
                      'Every CP is plotted; consult TXT/JSON for the full list.')

    delta_d = float(np.linalg.norm(np.asarray(box['end_base']) - np.asarray(box['origin'])))
    end_handle = Line2D([], [], linestyle='None', alpha=0)
    handles.append(end_handle)
    end_h = f"{to_height:.2f} m" if to_height is not None else "unavailable"
    labels.append(f"END: Pole {to_id} (h={end_h}, Δd={delta_d:.2f} m)")
    handlers[end_handle] = PoleLegend(to_id)

    # Pole labels inside the plot.
