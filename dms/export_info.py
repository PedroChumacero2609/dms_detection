def valid_wire(wire):
    if wire.get('point_min') is None or wire.get('point_max') is None:
        return False
    try:
        a, b, c = wire_coeffs(wire)
        return np.isfinite([a, b, c]).all() and np.max(np.abs([a, b, c])) > 1e-9
    except (KeyError, ValueError, TypeError):
        return False


def wire_coeffs(wire):
    eq = wire['equation']
    return tuple(np.array([float(eq[axis][key]) for axis in ('x', 'y', 'z')])
                 for key in ('a', 'b', 'c'))


def wire_points(wire, t):
    a, b, c = wire_coeffs(wire)
    t = np.asarray(t, dtype=float)
    return t[..., None] ** 2 * a + t[..., None] * b + c


def wire_frame(wire):
    a, b, _ = wire_coeffs(wire)
    n = np.cross(a, b)
    if np.linalg.norm(n) >= 1e-12 and np.linalg.norm(a) >= 1e-12:
        n /= np.linalg.norm(n)
        v = a / np.linalg.norm(a)
    else:
        tangent = a + b
        if np.linalg.norm(tangent) < 1e-12:
            return None
        tangent /= np.linalg.norm(tangent)
        ref = np.array([0., 0., 1.])
        if abs(tangent @ ref) > .98:
            ref = np.array([0., 1., 0.])
        n = np.cross(ref, tangent)
        n /= np.linalg.norm(n)
        v = np.cross(tangent, n)
        v /= np.linalg.norm(v)
    return n, v


def project_points_transverse(points, wire, cls):
    """Superpose all t frames at the conductor origin, preserving saved levels."""
    if len(points) == 0:
        return np.empty((0, 2))
    frame = wire_frame(wire)
    if frame is None:
        return np.empty((0, 2))
    a, b, c = wire_coeffs(wire)
    n, v = frame
    centers = wire_points(wire, np.linspace(0, 1, 161))
    nearest_sample = cKDTree(centers).query(points, workers=1)[1]
    t = nearest_sample.astype(float) / 160.0
    # Refine approximate Euclidean closest t by damped Newton steps.
    for _ in range(8):
        residual = t[:, None] ** 2 * a + t[:, None] * b + c - points
        derivative = 2 * t[:, None] * a + b
        gradient = np.einsum('ij,ij->i', residual, derivative)
        hessian = np.einsum('ij,ij->i', derivative, derivative) + 2 * (residual @ a)
        update = np.divide(gradient, hessian, out=np.zeros_like(t),
                           where=np.abs(hessian) > 1e-12)
        t = np.clip(t - np.clip(update, -.1, .1), 0., 1.)
    if cls in FIGURE_LEVELS:
        # The asymmetric figure is projected on its original parabola frame.
        m = np.cross(n, v)
        m /= np.linalg.norm(m)
        aa, bb = float(a @ m), float(b @ m)
        cc = (c - points) @ m
        if abs(aa) < 1e-14:
            roots = [(-cc / bb)] if abs(bb) > 1e-14 else []
        else:
            disc = bb*bb - 4*aa*cc
            sq = np.sqrt(np.maximum(disc, 0.))
            roots = [np.where(disc >= 0., (-bb - sq)/(2*aa), np.nan),
                     np.where(disc >= 0., (-bb + sq)/(2*aa), np.nan)]
        best_dist = np.full(len(t), np.inf)
        for root in roots:
            valid = np.isfinite(root) & (root >= -1e-6) & (root <= 1. + 1e-6)
            tt = np.clip(root, 0., 1.)
            diff = points - wire_points(wire, tt)
            dist = np.einsum('ij,ij->i', diff, diff)
            better = valid & (dist < best_dist)
            t[better] = tt[better]
            best_dist[better] = dist[better]
    offsets = points - wire_points(wire, t)
    return np.column_stack((offsets @ n, offsets @ v))


def full_shape_1(r2, r3):
    top_t = np.linspace(np.pi, 0, FIGURE_PATH_RES)
    top = np.column_stack((r2 * np.cos(top_t), r2 * np.sin(top_t)))
    y3 = -np.sqrt(max(r3*r3 - r2*r2, 0.))
    t3, t4 = np.arctan2(y3, r2), np.arctan2(y3, -r2)
    bot_t = np.linspace(t3, t4, FIGURE_PATH_RES)
    bottom = np.column_stack((r3 * np.cos(bot_t), r3 * np.sin(bot_t)))
    return np.vstack((top, bottom))


def level_shapes(cls, level):
    if cls in SNAKE_LEVELS:
        r = SNAKE_LEVELS[cls][level]
        t = np.linspace(0, 2 * np.pi, 193)
        return [np.column_stack((r * np.cos(t), r * np.sin(t)))]
    r1, r2, r3, length = FIGURE_PARAMS[cls]
    if level == 0:
        t = np.linspace(0, 2*np.pi, 193)
        polys = [np.column_stack((r1 * np.cos(t), r1 * np.sin(t)))]
    elif level == 1:
        t = np.linspace(0, 2*np.pi, 193)
        inner = np.column_stack((r1*np.cos(t), r1*np.sin(t)))
        polys = [full_shape_1(r2, r3), inner]
    elif level == 2:
        y3 = -np.sqrt(max(r3*r3-r2*r2, 0.))
        t = np.linspace(np.arctan2(y3, r2), np.arctan2(y3, -r2), FIGURE_PATH_RES)
        arc = np.column_stack((r3*np.cos(t), r3*np.sin(t)))
        polys = [np.vstack(([r2, -r3], arc, [-r2, -r3]))]
    else:
        polys = [np.array([[r2,-r3], [r2,-length-r3], [-r2,-length-r3], [-r2,-r3]])]
    return [np.vstack((poly, poly[0])) if not np.allclose(poly[0], poly[-1]) else poly
            for poly in polys]


class NumberLegend(HandlerBase):
    def __init__(self, number, color):
        super().__init__()
        self.number, self.color = str(number), color

