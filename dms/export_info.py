def section_transverse(path, section, cls, wires, xyz, props, max_points=MAX_TRANSVERSE_POINTS):
    sid = int(section['section_id'])
    accepted_labels = [DMS_LABELS[cls], CP_LABELS[cls]]
    ids = np.flatnonzero((props['section_id'] == sid) & (props['is_dms'] == 1) &
                         np.isin(props['class'], accepted_labels))
    if not len(ids) or not wires:
        return False
    if len(ids) > max_points:
        cp = ids[props['class'][ids] == CP_LABELS[cls]]
        other = ids[props['class'][ids] != CP_LABELS[cls]]
        n = max(0, max_points-len(cp))
        if len(other) > n:
            other = other[np.linspace(0, len(other)-1, n, dtype=np.int64)] if n else other[:0]
        ids = np.sort(np.r_[cp, other])
    levels = list(range(len(SNAKE_LEVELS[cls]))) if cls in SNAKE_LEVELS else FIGURE_LEVELS[cls]
    outlines = {lvl: level_shapes(cls, lvl) for lvl in levels}
    all_points = np.vstack([p for group in outlines.values() for p in group])
    margin = np.maximum(.55, .10 * (all_points.max(axis=0) - all_points.min(axis=0)))
    xlim = (float(all_points[:, 0].min()-margin[0]), float(all_points[:, 0].max()+margin[0]))
    ylim = (float(all_points[:, 1].min()-margin[1]), float(all_points[:, 1].max()+margin[1]))
    n = len(wires)
    fig, axes = plt.subplots(1, n, figsize=(max(7., 5.2*n), 5.8),
                             squeeze=False, sharex=True, sharey=True)
    axes = axes.ravel()
    for ax, wire in zip(axes, wires):
        wid = wire_number(wire['wire_id'])
        own = ids[props['wire_id'][ids] == wid]
        pts = xyz[own]
        uv = project_points_transverse(pts, wire, cls)
        for lvl in levels:
            mask = props['level_id'][own] == lvl
            if len(uv) and np.any(mask):
                ax.scatter(uv[mask, 0], uv[mask, 1], s=9,
                           c=LEVEL_COLOR[lvl], alpha=.65,
                           linewidths=0, rasterized=True, zorder=4)
            for outline in outlines[lvl]:
                ax.plot(outline[:, 0], outline[:, 1], c='black', lw=1.5, zorder=5)
        ax.plot(0., 0., '+', c='black', ms=9, mew=1.5, zorder=8)
        ax.set_title(f'Wire L{wid} | {len(own):,} points', fontsize=11, weight='bold')
        ax.set_xlim(*xlim); ax.set_ylim(*ylim)
        ax.set_aspect('equal', adjustable='box')
        ax.set_xlabel('u local (m)')
        ax.set_ylabel('v local (m)')
        ax.grid(alpha=.16)
    handles = [Line2D([], [], color='black', lw=1.5),
               Line2D([], [], linestyle='None', marker='+', color='black')]
    labels = ['Complete level boundaries', 'Wire center']
    for lvl in levels:
        handles.append(Line2D([], [], linestyle='None', marker='o', markersize=7,
                              markerfacecolor=LEVEL_COLOR[lvl], markeredgecolor='none'))
        labels.append(f'Level {lvl}')
    # Transverse panels have independent axes; reserve a separate bottom legend.
    fig.set_size_inches(max(7., 5.2*n), 6.5, forward=True)
    fig.subplots_adjust(left=.08, right=.98, top=.81, bottom=.27, wspace=.25)
    fig.suptitle(f"Collision {sid} - {CLASS_NAMES.get(cls, cls)}\n"
                 f"Poles {section['from_pole']}-{section['to_pole']}", fontsize=13, weight='bold')
    fig.legend(handles, labels, loc='lower center', ncol=min(3, len(labels)),
               bbox_to_anchor=(.5, .05), frameon=False, fontsize=9)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=180, bbox_inches='tight', pad_inches=.18, facecolor='white')
    plt.close(fig)
    return True


def format_cartesian(pt):
    return f'X={pt[0]:.4f} m | Y={pt[1]:.4f} m | Z={pt[2]:.4f} m'


def format_gps(coords):
    return f'{coords[0]:.8f}, {coords[1]:.8f}' if coords is not None else 'unavailable'


def export_txt(path, section, box, entries, pole_gps):
    a, b = int(section['from_pole']), int(section['to_pole'])
    lines = ['='*78, 'DMS - COLLISION LOCATION REPORT',
             f"Section: {a}_{b} | From pole {a} to pole {b}",
             f"Collision section number: {section['section_id']}", '='*78, '',
             f'START POLE | ID: {a}',
             f"  Cartesian position    : {format_cartesian(box['origin'])}",
             f"  Geographic Coordinates: {format_gps(pole_gps.get(a))}",
             f"  Pole height           : {box['from_height']:.2f} m" if box['from_height'] is not None else '  Pole height           : unavailable',
             '-'*78,
             f'DETECTED PHYSICAL OBJECTS: {len(section["collisions"])}',
             f'CRITICAL POINTS: {len(entries)}', '']
    for item in entries:
        obj = item['object']
        lines += ['='*78,
                  f"DMS CP {item['number']} | object_id={item['object_id']} | Class: {obj['class_name']}",
                  '='*78,
                  f"  Original class ID: {obj['original_class_id']} | # DMS: {obj['# DMS']}",
                  f"  Total DMS points : {obj['num_points']:,}",
                  f"  Volume           : {obj['volume_m3']:.5f} m^3",
                  f"  Point density    : {obj['density_pts_m3']:.5f} pts/m^3" if obj['density_pts_m3'] is not None else '  Point density    : unavailable',
                  f"  Centroid         : {format_cartesian(obj['centroid'])}",
                  f"  CRITICAL POINT   : {item['number']} | cable L{item['wire']} | level {item['level']}",
                  f"  min_dist_L{item['wire']}   : {item['min_dist']:.5f} m",
                  f"  Cartesian XYZ    : {format_cartesian(item['xyz'])}",
                  f"  Geographic Coordinates (approx.): {format_gps(item['gps'])}",
                  f"  Local section XYZ: x'={item['local'][0]:.4f} m | y'={item['local'][1]:.4f} m | z'={item['local'][2]:.4f} m",
                  '  AFFECTED WIRES / LEVELS']
        for cable, wire_data in sorted(obj['wires_affected'].items()):
            for level, record in sorted(wire_data['levels'].items()):
                lines.append(f"    {cable}, {level}: {record['num_points']:,} points")
        lines.append('')
    lines += ['-'*78, '', f'END POLE | ID: {b}',
              f"  Cartesian position    : {format_cartesian(box['end_base'])}",
              f"  Geographic Coordinates: {format_gps(pole_gps.get(b))}",
              f"  Pole height           : {box['to_height']:.2f} m" if box['to_height'] is not None else '  Pole height           : unavailable',
              '-'*78, '']
    path.write_text('\n'.join(lines), encoding='utf-8')


def collision_class_slug(name):
    clean = unicodedata.normalize('NFKD', str(name))
    clean = clean.encode('ascii', 'ignore').decode('ascii').lower()
    return re.sub(r'[^a-z0-9]+', '_', clean).strip('_') or 'unknown'


def resolve_path(base, *pieces):
    return Path(os.path.join(str(base), *(str(s) for s in pieces))).resolve()


def main():
    """Export individual section deliverables using top-of-file settings only."""
    if MAX_TRANSVERSE_POINTS < 1:
        raise ValueError('MAX_TRANSVERSE_POINTS must be positive')
    cfg = read_json(CONFIG_PATH)
    configure_labels(cfg)
    # Resolve all paths relative to the project configuration file.
    base = Path(CONFIG_PATH).resolve().parent
    collision_dir = Path(OUTPUT_DIR).resolve() if OUTPUT_DIR else resolve_path(base, cfg['collision_dir'])
    data_dir = resolve_path(base, cfg['data_dir'])
    output_dir = resolve_path(base, cfg['output_dir'])
    ply_path = Path(INPUT_PLY).resolve() if INPUT_PLY else resolve_path(base, cfg['collision_dir'], cfg['input_ply_new'])
    report_path = Path(INPUT_JSON).resolve() if INPUT_JSON else resolve_path(base, cfg['collision_dir'], cfg['zones_report_json'])
    pole_path = output_dir / cfg['poles_final']
    wire_path = output_dir / cfg['wires_final']
    gps_path = data_dir / cfg['coords_txt']
    for p in (ply_path, report_path, pole_path, wire_path):
        if not p.is_file():
            raise FileNotFoundError(f'Missing input: {p}')
    report = read_json(report_path)
    if not isinstance(report, dict) or not isinstance(report.get('sections'), list):
        raise ValueError('Report must contain a sections list')
    poles = read_json(pole_path)
    if isinstance(poles, dict):
        poles = list(poles.values())
    pole_ids = {norm_id(field_of(p, 'Pole_ID')) for p in poles}
    pole_map = {pid: resolved for pid in pole_ids if pid is not None
                if (resolved := resolve_pole(poles, pid)) is not None}
    wires_data = read_json(wire_path)
    wire_map = {str(rec.get('section_id')): rec for rec in wires_data}
    pole_gps = load_gps(gps_path)
    xyz, props = read_ply(ply_path)
    recon_idx = np.flatnonzero(np.isin(props['class'], list(RECON)))
    log(f'Loaded {len(xyz):,} total points, {len(recon_idx):,} reconstruction points')
    count = 0
    for section in report['sections']:
        sid = int(section['section_id'])
        a, b = int(section['from_pole']), int(section['to_pole'])
        if a not in pole_map or b not in pole_map:
            warn(f'Section {sid}: missing pole {a} or {b}; skipped')
            continue
        box = section_box(pole_map[a], pole_map[b])
        entries = cp_records(section, box, xyz, props, pole_gps)
        if not entries:
            log(f'Section {sid} ({a}_{b}): no CPs; skipped')
            continue
        name = f'collision_{sid:02d}'
        subdir = collision_dir / name
        subdir.mkdir(parents=True, exist_ok=True)
        # Export this section verbatim with the same compact schema as the master report.
        section_json = subdir / f'collision_report_{sid:02d}.json'
        with section_json.open('w', encoding='utf-8') as out:
            json.dump({'sections': [section]}, out, ensure_ascii=False, indent=2, allow_nan=False)
        txt_path = subdir / f'collision_gps_{sid:02d}.txt'
        export_txt(txt_path, section, box, entries, pole_gps)
        # Original TOP, without cartographic background.
        view_section(subdir / f'collision_graphic_top_{sid:02d}.png',
                     section, box, xyz, props, entries, recon_idx,
                     axis_y='y', pole_gps=pole_gps, show_street_map=False)
        # Wider schematic TOP map only; do not change the original TOP or PROFILE box.
        map_box = dict(box, width=TOP_MAP_BOX_WIDTH)
        view_section(subdir / f'collision_graphic_top_map_{sid:02d}.png',
                     section, map_box, xyz, props, entries, recon_idx,
                     axis_y='y', pole_gps=pole_gps, show_street_map=True)
        view_section(subdir / f'collision_graphic_profile_{sid:02d}.png',
                     section, box, xyz, props, entries, recon_idx, axis_y='z')
        wires_section = wire_map.get(f'{a}_{b}') or wire_map.get(f'{b}_{a}')
        wires = ([w for w in wires_section.get('wires', []) if valid_wire(w)]
                 if wires_section else [])
        wires.sort(key=lambda w: wire_number(w['wire_id']) or 99)
        for cls in sorted({int(o['original_class_id']) for o in section['collisions']}):
            if cls not in DMS_CLASSES:
                warn(f'Unsupported transverse class {cls} in section {sid}')
                continue
            slug = collision_class_slug(CLASS_NAMES.get(cls, str(cls)))
            transverse_path = subdir / f'collision_{a}_{b}_{slug}.png'
            if not section_transverse(transverse_path, section, cls, wires, xyz, props,
                                      max_points=MAX_TRANSVERSE_POINTS):
                warn(f'No transverse data for section {sid}, class {cls}')
        count += 1
        log(f'Section {sid} ({a}_{b}): TOP original, TOP map, PROFILE, TXT, JSON and transverse figures -> {subdir}')
    log(f'Completed export for {count} collision sections. Classification was not rerun.')


if __name__ == '__main__':
    main()