def norm_id(value):
    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return None


def field_of(p, key):
    return p.get(key, p.get('Info', {}).get(key))


def resolve_pole(poles, pole_id):
    matching = []
    for p in poles:
        pid = field_of(p, 'Pole_ID')
        if pid is not None and norm_id(pid) == pole_id:
            matching.append(p)
    if not matching:
        return None
    bases, mean_bases, heights, vectors = [], [], [], []
    for p in matching:
        b1, b2 = field_of(p, 'Base_1'), field_of(p, 'Base_2')
        main = field_of(p, 'Base')
        if field_of(p, 'Type') == 'Biposte' and b1 is not None and b2 is not None:
            a, b = np.asarray(b1, dtype=float), np.asarray(b2, dtype=float)
            bases.extend([a, b]); mean_bases.append((a + b) / 2)
        else:
            b = main if main is not None else b1
            if b is not None:
                arr = np.asarray(b, dtype=float)
                bases.append(arr); mean_bases.append(arr)
        if field_of(p, 'height') is not None:
            heights.append(float(field_of(p, 'height')))
        if field_of(p, 'unit_vector') is not None:
            vectors.append(np.asarray(field_of(p, 'unit_vector'), dtype=float))
    if not mean_bases:
        return None
    uv = np.mean(vectors, axis=0) if vectors else np.array([0., 0., 1.])
    uv = uv / np.linalg.norm(uv) if np.linalg.norm(uv) > 1e-9 else np.array([0., 0., 1.])
    return {'bases': bases, 'base_avg': np.mean(mean_bases, axis=0),
            'height': float(np.mean(heights)) if heights else None,
            'dir': uv}


def choose_base(pole, other):
    arr = pole['bases']
    if len(arr) <= 1:
        return np.asarray(arr[0] if arr else pole['base_avg'], dtype=float)
    # Preserve bipole base-selection behavior of zones.py.
    return np.asarray(max(arr, key=lambda a: float(np.linalg.norm(a - other))), dtype=float)


def section_box(start_pole, end_pole):
    """Pole-first local frame: Z' follows mean pole tilt, X' is orthogonalized.

    Y' = Z' cross X'. Ground in PROFILE is the straight line joining
    the two selected pole bases; it is not a LiDAR-derived terrain profile.
    """
    start = choose_base(start_pole, end_pole['base_avg'])
    end = choose_base(end_pole, start)
    start = choose_base(start_pole, end)

    # Preserve the mean pole direction as the primary (vertical) axis.
    hdir = 0.5 * (np.asarray(start_pole['dir'], dtype=float) +
                  np.asarray(end_pole['dir'], dtype=float))
    if np.linalg.norm(hdir) < 1e-6:
        hdir = np.array([0., 0., 1.])
    hdir = hdir / np.linalg.norm(hdir)

    # Project the pole-to-pole vector onto the plane normal to Z'.
    delta = end - start
    ldir = delta - np.dot(delta, hdir) * hdir
    if np.linalg.norm(ldir) < 1e-6:
        for fallback in (np.array([1., 0., 0.]), np.array([0., 1., 0.])):
            ldir = fallback - np.dot(fallback, hdir) * hdir
            if np.linalg.norm(ldir) >= 1e-6:
                break
    ldir = ldir / np.linalg.norm(ldir)
    wdir = np.cross(hdir, ldir)
    wdir = wdir / np.linalg.norm(wdir)

    length = max(float(np.dot(delta, ldir)), 1e-6)
    z2_local = float(np.dot(delta, hdir))
    from_h = float(start_pole['height'] or 0.)
    to_h = float(end_pole['height'] or 0.)
    # Include both pole tops even when their bases have different local heights.
    height = max(from_h, z2_local + to_h, z2_local, 0.) + BOX_HEIGHT_MARGIN
    R = np.column_stack((ldir, wdir, hdir))
    return {'origin': start, 'end_base': end, 'length_axis': length,
            'height': height, 'width': BOX_WIDTH,
            'from_height': start_pole['height'], 'to_height': end_pole['height'],
            'R': R, 'z2_local': z2_local}


def world_to_local(points, box):
    return (np.asarray(points, dtype=float) - box['origin']) @ box['R']


def inside_box(local, box):
    return (np.isfinite(local).all(axis=1) &
            (local[:, 0] >= BOX_X_MIN) &
            (local[:, 0] <= box['length_axis'] + BOX_X_MAX) &
            (np.abs(local[:, 1]) <= box['width'] / 2) &
            (local[:, 2] >= 0) & (local[:, 2] <= box['height']))


def load_gps(path):
    result = {}
    if not path.is_file():
        warn(f'GPS file not found: {path}; TXT will include cartesian positions')
        return result
    for line in path.read_text(encoding='utf-8').splitlines():
        m = re.search(r'Pole\s+(\d+):\s*([-\d.]+),\s*([-\d.]+)', line)
        if m:
            result[int(m.group(1))] = (float(m.group(2)), float(m.group(3)))
    return result


def interpolate_gps(start, end, x, length):
    if start is None or end is None:
        return None
    t = float(np.clip(x / max(length, 1e-9), 0., 1.))
    return (start[0] + t * (end[0] - start[0]),
            start[1] + t * (end[1] - start[1]))


